//! Install only a guarded TUI entrypoint in this ship's native plugin folder.
use anyhow::{Context, Result, ensure};
use std::{fs, io::Write, os::unix::fs::OpenOptionsExt, path::Path};

const MARKER: &str = "// Generated by Privateer: attended OpenCode V2 mail\n";
const PACKAGE: &str =
    "{\"name\":\"@privateer/attended-mail-v2\",\"private\":true,\"type\":\"module\"}\n";

pub fn install(folder: &Path, plugins: &Path) -> Result<()> {
    let module = plugins.join("attended-opencode-v2/tui.tsx");
    ensure!(module.is_file(), "OpenCode V2 attended mail plugin missing");
    let config = folder.join(".opencode");
    let parent = config.join("plugins");
    let directory = parent.join("privateer-attended-v2");
    let entry = directory.join("tui.js");
    let package = directory.join("package.json");
    for path in [&config, &parent, &directory, &entry, &package] {
        ensure!(
            !path
                .symlink_metadata()
                .is_ok_and(|m| m.file_type().is_symlink()),
            "OpenCode V2 mail entrypoint cannot be a symlink"
        );
    }
    let mut url = String::from("file://");
    for byte in module
        .to_str()
        .context("plugin path must be UTF-8")?
        .bytes()
    {
        if byte.is_ascii_alphanumeric() || b"/-_.~".contains(&byte) {
            url.push(byte as char);
        } else {
            use std::fmt::Write;
            write!(url, "%{byte:02X}")?;
        }
    }
    let source = format!(
        "{MARKER}export {{ default }} from {};\n",
        serde_json::to_string(&url)?
    );
    for path in [&entry, &package] {
        if path.exists() {
            ensure!(
                fs::metadata(path)?.len() <= 65_536,
                "native mail entrypoint too large"
            );
        }
        match fs::read_to_string(path) {
            Ok(old) => {
                ensure!(
                    (path == &entry && old.starts_with(MARKER)) || old == PACKAGE,
                    "refusing to replace a custom OpenCode plugin file: {}",
                    path.display()
                );
            }
            Err(error) if error.kind() == std::io::ErrorKind::NotFound => {}
            Err(error) => return Err(error.into()),
        }
    }
    for (path, body) in [(&entry, source.as_str()), (&package, PACKAGE)] {
        if fs::read_to_string(path).is_ok_and(|old| old == body) {
            continue;
        }
        fs::create_dir_all(&directory)?;
        let temporary = directory.join(format!(".privateer-{}", uuid::Uuid::new_v4()));
        let result = (|| -> Result<()> {
            let mut file = fs::OpenOptions::new()
                .write(true)
                .create_new(true)
                .mode(0o600)
                .open(&temporary)?;
            file.write_all(body.as_bytes())?;
            file.sync_all()?;
            fs::rename(&temporary, path)?;
            Ok(())
        })();
        if result.is_err() {
            let _ = fs::remove_file(temporary);
        }
        result?;
    }
    Ok(())
}
